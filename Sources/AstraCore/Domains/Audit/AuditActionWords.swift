    /// The label for `action`, or nil when it keeps its raw name. A decision
    /// on any plugin's plan (`network.<plugin>.approve`) reads as one label.
    public static func label(for action: String) -> String? {
        let name = action.trimmingCharacters(in: .whitespaces)
        if name.hasPrefix("network."), name.count > "network.".count {
            for (verb, label) in [("approve", "Plan approved"), ("reject", "Plan rejected"), ("dismiss", "Plan dismissed")] {
                let suffix = ".\(verb)"
                if name.hasSuffix(suffix), name.count > "network.".count + suffix.count { return label }
            }
        }
        return labels[name]
    }

    /// The label, or the raw action when it has none.
    public static func words(for action: String) -> String {
        label(for: action) ?? action
    }
